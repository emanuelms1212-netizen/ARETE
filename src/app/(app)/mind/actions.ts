'use server';

import { revalidatePath } from 'next/cache';
import { getCurrentUser } from '@/auth';
import { clientToken, type DrillItem, type MindKind, type MindSession } from '@/domain';
import { withUser } from '@/persistence';
import { resolveCurrentDay } from '../current-day';

/**
 * The Mind module's writes.
 *
 * Same shape as the focus timer's: these return the session, because the
 * player has to render from the answer rather than wait for a revalidation
 * round-trip. The user comes from the session and the date from the account's
 * own timezone; the only thing taken from the client is which practice, and
 * the repository refuses one from a pack the account has not chosen.
 */
async function account() {
  const user = await getCurrentUser();
  if (!user) throw new Error('Signed out.');
  return user;
}

export async function startMindAction(input: {
  kind: MindKind;
  practiceSlug: string;
  plannedMinutes?: number | null;
  plannedRounds?: number | null;
  attemptToken: string;
}): Promise<MindSession> {
  const user = await account();
  const startedAt = new Date();

  const session = await withUser(user.id, async (repository) => {
    const { localDate, timeZone } = await resolveCurrentDay(repository, user);
    return repository.startMindSession(user.id, {
      kind: input.kind,
      practiceSlug: input.practiceSlug,
      localDate,
      timeZone,
      startedAt,
      plannedMinutes: input.plannedMinutes ?? null,
      plannedRounds: input.plannedRounds ?? null,
      // One token per attempt, generated by the client — the same lesson as
      // the focus timer (D50): a token derived from the clock collides with a
      // session that has just ended.
      clientToken: clientToken('mind-start', input.attemptToken),
    });
  });

  revalidatePath('/mind');
  return session;
}

export async function pauseMindAction(kind: MindKind): Promise<MindSession> {
  const user = await account();
  return withUser(user.id, (repository) => repository.pauseMindSession(user.id, kind, new Date()));
}

export async function resumeMindAction(kind: MindKind): Promise<MindSession> {
  const user = await account();
  return withUser(user.id, (repository) => repository.resumeMindSession(user.id, kind, new Date()));
}

export async function finishMindAction(input: {
  kind: MindKind;
  status: 'completed' | 'abandoned';
  rating?: number | null;
  reflection?: string | null;
  rounds?: number | null;
  items?: readonly DrillItem[];
}): Promise<MindSession | null> {
  const user = await account();

  const session = await withUser(user.id, (repository) =>
    repository.finishMindSession(user.id, { ...input, at: new Date() }),
  );

  revalidatePath('/mind');
  revalidatePath('/today');
  return session;
}

export async function setPackChosenAction(input: {
  packSlug: string;
  chosen: boolean;
}): Promise<void> {
  const user = await account();

  await withUser(user.id, (repository) =>
    repository.setPackChosen(user.id, input.packSlug, input.chosen),
  );

  revalidatePath('/mind');
}
