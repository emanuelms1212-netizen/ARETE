'use server';

import { revalidatePath } from 'next/cache';
import { getCurrentUser } from '@/auth';
import { clientToken, type FocusKind, type FocusSession } from '@/domain';
import { withUser } from '@/persistence';
import { resolveCurrentDay } from '../current-day';

/**
 * The focus timer's writes.
 *
 * The timer's state lives on the server, which is the whole point: a refresh,
 * a second tab or a dead battery all recover the same session because none of
 * them is where the elapsed time was being kept.
 *
 * These return the session rather than `void`, unlike the day's actions. A
 * timer has to render immediately from the answer — waiting for a revalidation
 * round-trip to find out whether the clock started would show a visible stall
 * on the one control where that is most obvious.
 */
async function account() {
  const user = await getCurrentUser();
  if (!user) throw new Error('Signed out.');
  return user;
}

export async function startFocusAction(input: {
  plannedMinutes: number;
  kind: FocusKind;
  preset?: string | null;
  taskId?: string | null;
  goalId?: string | null;
  /**
   * One token per start *attempt*, generated by the client.
   *
   * This was derived on the server from the date, the task and the current
   * minute, which is wrong in a way that only shows up under load: finish a
   * session and start an identical one in the same minute, and the token
   * matches the finished row, so the idempotency check hands back a session
   * that has already ended. A token that identifies the attempt survives a
   * retry of that attempt without colliding with the next one.
   */
  attemptToken: string;
}): Promise<FocusSession> {
  const user = await account();
  const startedAt = new Date();

  const session = await withUser(user.id, async (repository) => {
    const { localDate, timeZone } = await resolveCurrentDay(repository, user);
    return repository.startFocusSession(user.id, {
      localDate,
      timeZone,
      plannedMinutes: input.plannedMinutes,
      kind: input.kind,
      preset: input.preset ?? null,
      taskId: input.taskId ?? null,
      goalId: input.goalId ?? null,
      startedAt,
      // Namespaced, so a client-supplied value cannot collide with a token
      // this app generates for some other kind of write.
      clientToken: clientToken('focus-start', input.attemptToken),
    });
  });

  revalidatePath('/today');
  return session;
}

export async function getRunningFocusAction(): Promise<FocusSession | null> {
  const user = await account();
  return withUser(user.id, (repository) => repository.getRunningFocusSession(user.id));
}

export async function pauseFocusAction(): Promise<FocusSession> {
  const user = await account();
  return withUser(user.id, (repository) => repository.pauseFocusSession(user.id, new Date()));
}

export async function resumeFocusAction(): Promise<FocusSession> {
  const user = await account();
  return withUser(user.id, (repository) => repository.resumeFocusSession(user.id, new Date()));
}

export async function finishFocusAction(input: {
  status: 'completed' | 'abandoned';
  reflection?: string | null;
}): Promise<FocusSession | null> {
  const user = await account();

  const session = await withUser(user.id, (repository) =>
    repository.finishFocusSession(user.id, {
      at: new Date(),
      status: input.status,
      reflection: input.reflection ?? null,
    }),
  );

  revalidatePath('/today');
  return session;
}
